    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        String sqlInsert = """
                           INSERT INTO produto
                           (descricao,estoque,valor_venda)
                           VALUES(?,?,?)
                           """;
        
        try{
            Connection conex = conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sqlInsert);
            
           
            
            String descricao = txtDescricao.getText();
            
             
            int estoque = Integer.parseInt(spEstoque.getValue().toString());
            Double valor = Double.parseDouble(txtValorVenda.getText());
            
            stmt.setString(1, descricao);
            stmt.setInt(2, estoque);
            stmt.setDouble(3,valor);
            
                     
            int linhas = stmt.executeUpdate();
            
            if (linhas>0){
                JOptionPane.showMessageDialog(this,"Produto cadastrado");
            }
        }catch (SQLException erro){
            JOptionPane.showMessageDialog(this, "ERRO " + erro);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

