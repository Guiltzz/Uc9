    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        
        
        String nome = txtNome.getText().trim();
        String telefone = txtNumero.getText();
        String curso = cbMateria.getSelectedItem().toString();
        String idade = spIdade.getValue().toString();
        
        if(txtNome.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(this, "Informe seu nome :");
            txtNome.requestFocus();
            return;
        }
        
        if (cbMateria.getSelectedIndex() == 0){
            JOptionPane.showMessageDialog(this, "Selecione um curso");
            cbMateria.requestFocus();
            return;
        }
        
        if (!rbManha.isSelected() && !rbNoite.isSelected() && !rbTarde.isSelected()){
            JOptionPane.showMessageDialog(this, "Escolha um turno");
            return;
        }
        
        String turno = "";
        if(rbManha.isSelected()){
            turno = "Manhã";
            
        }if (rbTarde.isSelected()){
        turno = "Tarde";
    
        }if (rbNoite.isSelected()){
            turno = "Noite";
        }
        
        DefaultTableModel modelo = (DefaultTableModel) tabProfessores.getModel();
        modelo.addRow(new String []{nome,telefone,curso,turno,idade});
        limparCampos();
    }//GEN-LAST:event_btnAddActionPerformed

