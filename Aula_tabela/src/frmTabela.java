    private void btnApagarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnApagarActionPerformed
        int linha = tblAlunos.getSelectedRow();
        if(linha <0){
            JOptionPane.showMessageDialog(this, "Selecione um aluno");
            return;
        }
        
        int resposta = JOptionPane.showConfirmDialog(this, "Deseja excluir o registro selecionado ? ","Confirmação", JOptionPane.YES_NO_OPTION);
        if(resposta ==  JOptionPane.YES_OPTION){
            DefaultTableModel modelo = (DefaultTableModel)tblAlunos.getModel();
            modelo.removeRow(linha);
        }
    }//GEN-LAST:event_btnApagarActionPerformed

