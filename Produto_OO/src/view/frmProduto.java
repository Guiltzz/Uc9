    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        Produto produto = new Produto();
        
        String codigo = txtCodigo.getText();
        
        produto.setId(Integer.parseInt(codigo));
        
        
        produto.setDescrição(txtDesc.getText().trim());
        
        //String qtde = spEstoque.getValue().toString();
        
        produto.setEstoque((Integer.parseInt( spEstoque.getValue().toString())));
        
        produto.setValorCompra(Double.parseDouble(txtValorVenda.getText().replace(",",".")));
        
        produto.setValorVenda(Double.parseDouble(txtValorCompra.getText().replace(",",".")));
        
        produto.setAtivo(cbAtivo.isSelected());
        
        ProdutoDAO.salvar(produto);
        
        JOptionPane.showMessageDialog(this, produto.getId() + "Mensagem" + produto.getDescrição());
        LimparCampos();
    }//GEN-LAST:event_btnSalvarActionPerformed

