    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
         String id = txtID.getText();
        Fornecedor fornecedor = new Fornecedor ();
        Fornecedor existente = FornecedorDAO.buscarID(Integer.parseInt(id));
        
        if(existente != null){
            JOptionPane.showMessageDialog(this,"Id invalido");
            return;
        }
        
        
       
        fornecedor.setId(Integer.parseInt(id));
        
        fornecedor.setRazaoSocial(txtRazao.getText().trim());
        fornecedor.setNomeFantasia(txtRazao.getText().trim());
        fornecedor.setCnpj(txtCNPJ.getText().trim());
        fornecedor.setEndereço(txtEndereço.getText().trim());
        fornecedor.setUf(cbUF.getSelectedItem().toString());
        
        fornecedor.setAtivo(cbAtivo.isSelected());
        FornecedorDAO.Salvar(fornecedor);
        
        
        
        
        
        JOptionPane.showMessageDialog(this, "Salvo");
        Limpar();
        atualizarTabela();
             
        
        
    }//GEN-LAST:event_btnSalvarActionPerformed

