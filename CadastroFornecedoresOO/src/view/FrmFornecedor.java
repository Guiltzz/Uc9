   private void atualizarTabela(){
        DefaultTableModel modelo = (DefaultTableModel) tabFornecedores.getModel();
        modelo.setRowCount(0);
        
        for (Fornecedor fornecedor: FornecedorDAO.listar()){
        String situacao = fornecedor.isAtivo() ? "Ativo" : "Inativo";
        modelo.addRow(new Object[]{fornecedor.getId(),fornecedor.getRazaoSocial(),fornecedor.getNomeFantasia(),fornecedor.getCnpj(),fornecedor.getEndereço(),fornecedor.getUf(),situacao
        });
          
        }
        
    }
   
   private void mostrarFornecedores(Fornecedor fornecedor){
        DefaultTableModel modelo = (DefaultTableModel) tabFornecedores.getModel();
        modelo.setRowCount(0);
        
        modelo.setColumnIdentifiers(
                new Object[]{
                "ID", "Razão Social", "Nome Fantasia", "CNPJ", "Endereço","UF","Situação"
        });
        
      if(fornecedor != null){
         String situacao = fornecedor.isAtivo() ? "Ativo" : "Inativo";
          modelo.addRow(new Object[]{fornecedor.getId(),fornecedor.getRazaoSocial(),fornecedor.getNomeFantasia(),fornecedor.getCnpj(),fornecedor.getEndereço(),fornecedor.getUf(),situacao
        });   
      }  
        
    }
   
