    private void btnPesquisaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisaActionPerformed
        String pesquisa = txtPesquisa.getText().trim();
        if(pesquisa.isEmpty()){
            JOptionPane.showMessageDialog(this, "Digite uma informação para Pesquisa");
            txtPesquisa.requestFocus();
            return;
        }
        
        String tipoPesquisa = cbPesquisa.getSelectedItem().toString();
        
        if(tipoPesquisa.equals("ID")){
            
        
        Fornecedor fornecedor = FornecedorDAO.buscarID(Integer.parseInt(pesquisa));
        
        if(fornecedor != null){
            List<Fornecedor> encontrados = new ArrayList();
            encontrados.add(fornecedor);
            mostrarFornecedores(fornecedor);
        }else{
            JOptionPane.showMessageDialog(this,"Produto não Encontrado!!");
        }
        }
    }//GEN-LAST:event_btnPesquisaActionPerformed

